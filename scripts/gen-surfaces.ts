#!/usr/bin/env bun
/**
 * Surface generator: serializes the tool face into discovery artifacts.
 * SKILL.md, Codex plugin, and the marketplace manifest derive from
 * surfaces/video.schema.json — the golden copy of the Rust schema
 * (`crates/harness/src/schema.rs`), kept current by the
 * `pinned_surface_schema_is_current` test. Run via `bun run gen:surfaces`.
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { version } = require('../packages/harness/package.json') as { version: string }

interface SchemaProp {
	description: string
	type?: string
	enum?: readonly string[]
	anyOf?: readonly unknown[]
}

interface ToolSchema {
	name: string
	description: string
	inputSchema: { properties: Record<string, SchemaProp>; required: readonly string[] }
}

const {
	description: VIDEO_TOOL_DESCRIPTION,
	inputSchema: VIDEO_INPUT_SCHEMA,
	tools: TOOLS,
} = require('../surfaces/video.schema.json') as {
	description: string
	inputSchema: { properties: Record<string, SchemaProp>; required: readonly string[] }
	tools: readonly ToolSchema[]
}

const toolByName = (name: string): ToolSchema => {
	const t = TOOLS.find((t) => t.name === name)
	if (t === undefined) throw new Error(`tool ${name} disappeared from the schema`)
	return t
}

const CONFIRM_TOOL = toolByName('video_confirm')

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const REPO_URL = 'https://github.com/durvia/agent-video'
const GENERATED = 'Generated by scripts/gen-surfaces.ts — do not edit.'

function emit(rel: string, content: string): void {
	const path = join(root, rel)
	mkdirSync(dirname(path), { recursive: true })
	writeFileSync(path, content)
	console.log(`wrote ${rel}`)
}

function emitJson(rel: string, body: unknown): void {
	emit(rel, `${JSON.stringify(body, null, 2)}\n`)
}

const props = VIDEO_INPUT_SCHEMA.properties
const desc = (key: string): string => {
	const p = props[key]
	if (p === undefined) throw new Error(`schema property ${key} disappeared`)
	return p.description
}

// ── SKILL.md ──

const skillMd = `---
name: agent-video
description: ${JSON.stringify(`${VIDEO_TOOL_DESCRIPTION} Use when the user shares a video file or URL to watch, summarize, or inspect.`)}
---

<!-- ${GENERATED} -->

# agent-video

Watch a video as frame grids: timestamped JPEG canvases a VLM can read
directly, with subtitles and key-frame metadata riding along.

## CLI path (preferred where you can run commands)

Grids are written as files and opened with your own image reader, so no
response-size ceiling applies. Same budget ladder, cached transcript and
decisions as the tool:

\`\`\`sh
npx -y @agent-video/cli probe video.mp4              # metadata + next calls
npx -y @agent-video/cli watch video.mp4 -o out/      # grids as files
npx -y @agent-video/cli watch video.mp4 -o out/ --from 1:23 --until 2:00 --look detailed
\`\`\`

- \`out/\` receives the grid JPEGs plus \`metadata.json\`: per-grid time
  ranges, key frames, and subtitle text. \`watch\` prints that document to
  stdout too.
- A decision the tool would ask a model to confirm needs \`--yes\` here.
- URLs: download first, then pass the local path.
- Raw core access remains \`process\` / \`extract\`; see \`--help\`.

## MCP path (when the host has no shell)

Register the stdio server and call the \`video\` tool — grid images arrive
directly in context, bounded by whatever response ceiling the host imposes:

\`\`\`json
{ "mcpServers": { "video": { "command": "npx", "args": ["-y", "@agent-video/cli", "mcp"] } } }
\`\`\`

Protocol — the response always tells you what to do next:

1. Call with only \`source\`. ${desc('source')}
2. \`"status": "plan"\` — probe summary plus \`recommended_calls\`; copy one
   argument object verbatim into the next call.
3. \`"status": "confirm_required"\` — the action needs explicit consent.
   Call \`video_confirm\` with the same \`source\` and one \`token\` copied
   from the response.
4. \`"status": "pending"\` — a background download is running; repeat the
   same call to poll.
5. \`"status": "failed"\` — \`error\` is model-presentable prose, \`kind\` the
   machine-readable class (\`bad_input\`, \`environment\`, \`transient\`,
   \`internal\`).
6. Success — a rendered grid is *not* a tagged body: one text block
   carrying time ranges, key frames, subtitles, and notices, followed by
   one JPEG image block per grid.

Refining parameters:

- \`from\` — ${desc('from')}
- \`until\` — ${desc('until')}
- \`look\` — ${desc('look')}
- \`strategy\` — ${desc('strategy')}
- \`want\` — ${desc('want')}
- \`raw\` — ${desc('raw')}

## URLs

On the MCP path, pass the URL as \`source\` — download and consent are
handled by the server. On the CLI path, fetch the file yourself first
(e.g. yt-dlp) and pass the local path.
`

